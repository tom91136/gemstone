package net.kurobako.gemstone.codegen

import scala.collection.mutable

/** Renders the typed modifier and operand domains of PTX and the report of where its sources disagree. */
object GeneratePTXDomains {
  case class Output(modifiers: String, operands: String, report: String)

  private class Interner[A] {
    private val ids          = mutable.HashMap.empty[A, Int]
    private val values       = mutable.ArrayBuffer.empty[A]
    def apply(value: A): Int = ids.getOrElseUpdate(value, { values += value; values.size - 1 })
    def result: Vector[A]    = values.toVector
  }

  def unresolved(derived: PTXOperandDomains.Derived): Vector[DomainFinding] =
    derived.findings.filter(_.resolution.isEmpty).distinct

  def render(derived: PTXOperandDomains.Derived): Output =
    Output(modifiers(derived), operands(derived), report(derived))

  /** Fails on the disagreements no rule resolves. */
  def check(derived: PTXOperandDomains.Derived): Unit = OperandDomain.requireResolved("PTX", unresolved(derived))

  private def lines(rows: Vector[String]): String = rows.map("    " + _).mkString(",\n")

  private def modifiers(derived: PTXOperandDomains.Derived): String = {
    val domains = Interner[PTXOperandDomains.Slot]()
    val rows    = derived.definitions.map { definition =>
      val forms = definition.forms.map { form =>
        ujson.Arr(
          ujson.Arr.from(form.required.map(slot => domains(slot))),
          ujson.Arr.from(form.optional.map(slot => domains(slot))),
          ujson.Arr.from(form.unordered),
          if (form.complete) 1 else 0,
          ujson.Arr.from(form.operands.map(operand =>
            ujson.Arr(operand.name, operand.constraint, if (operand.optional) 1 else 0)
          ))
        )
      }
      ujson.write(ujson.Arr(definition.caseName, definition.opcode, ujson.Arr.from(forms)))
    }
    val slots = domains.result.map(slot => ujson.write(ujson.Arr.from(slot.name +: slot.values)))
    s"{\n  \"domains\": [\n${lines(slots)}\n  ],\n  \"definitions\": [\n${lines(rows)}\n  ]\n}\n"
  }

  private def operands(derived: PTXOperandDomains.Derived): String = {
    def array(values: Iterable[ujson.Value]): ujson.Arr  = ujson.Arr.from(values)
    def matrix(value: PTXReferenceTables.Matrix): String = ujson.write(
      ujson.Obj(
        "columns" -> array(value.columns.map(ujson.Str(_))),
        "rows"    -> array(value.rows.map(row => ujson.Arr(row.label, array(row.cells.map(ujson.Str(_))))))
      )
    )
    val types = derived.types.map(row =>
      ujson.write(
        ujson.Arr(
          row.name,
          row.kind,
          row.bits,
          row.elements,
          row.element.getOrElse(""),
          array(row.declared.map(ujson.Str(_))),
          row.source
        )
      )
    )
    val special = derived.tables.special.map(row =>
      ujson.write(ujson.Arr(row.name, row.tpe, if (row.vector) 1 else 0, row.section))
    )
    val bindings = derived.rules.bindings.map(row =>
      ujson.write(
        ujson.Obj(
          "opcodes" -> array(row.opcodes.map(ujson.Str(_))),
          "any"     -> array(row.any.map(ujson.Str(_))),
          "fill"    -> row.fill,
          "at"      -> array(row.at.map((position, tpe) => ujson.Arr(position, tpe))),
          "section" -> row.cite.section
        )
      )
    )
    val values = derived.rules.values.map(row =>
      ujson.write(
        ujson.Obj(
          "opcodes"  -> array(row.opcodes.map(ujson.Str(_))),
          "any"      -> array(row.any.map(ujson.Str(_))),
          "all"      -> array(row.all.map(ujson.Str(_))),
          "none"     -> array(row.none.map(ujson.Str(_))),
          "position" -> row.position,
          "kind"     -> row.kind,
          "values"   -> array(row.values.map(value => ujson.Num(value.toDouble))),
          "elements" -> row.elements,
          "section"  -> row.cite.section
        )
      )
    )
    val agreement = ujson.write(
      ujson.Obj.from(derived.tables.agreement.rows.map(row =>
        row.label -> array(derived.tables.agreement.columns.zip(row.cells).map((column, cell) =>
          ujson.Arr(column, cell)
        ))
      ))
    )
    val sections = Vector(
      "types"    -> types,
      "special"  -> special,
      "bindings" -> bindings,
      "rules"    -> values
    )
    val named  = sections.map((name, rows) => s"""  ${ujson.write(name)}: [\n${lines(rows)}\n  ]""")
    val tables = Vector(
      s"""  "agreement": $agreement""",
      s"""  "source": ${matrix(derived.tables.source)}""",
      s"""  "destination": ${matrix(derived.tables.destination)}"""
    )
    (named ++ tables).mkString("{\n", ",\n", "\n}\n")
  }

  private val Rules = Vector(
    "# PTX operand domains",
    "",
    "Generated by `sbt codegen`; do not edit.",
    "",
    "## Rules",
    "",
    "- The syntax blocks decide the modifier slots: each `.name` of an opcode spelling is a slot, and the domain",
    "  definition of that name gives its values. A name without a definition is a slot of one value.",
    "- The fundamental and packed type tables give the types, widths and register declarations. Types the tables do",
    "  not list come from cited rows of the hand table, each quoting the sentence it rests on.",
    "- The type checking tables decide which operand types an instruction type accepts; the relaxed tables add the",
    "  widening that `ld`, `st` and `cvt` allow.",
    "- Prose range, alignment and operand type rules are hand rows. Generation fails if a row's section or quoted",
    "  sentence is missing from the pinned document.",
    "- A disagreement no rule resolves fails the build."
  )

  private val RuleHeader = Vector(
    "",
    "## Prose rules",
    "",
    "| opcode | operand | when | check | section |",
    "| --- | ---: | --- | --- | --- |"
  )

  private val FindingsHeader = Vector("", "## Findings", "")

  private def report(derived: PTXOperandDomains.Derived): String = {
    val forms    = derived.definitions.flatMap(_.forms)
    val allSlots = forms.flatMap(form => form.required ++ form.optional)
    val summary  = Vector(
      "",
      "## Summary",
      "",
      "| item | count |",
      "| --- | ---: |",
      s"| instruction definitions | ${derived.definitions.size} |",
      s"| syntax forms | ${forms.size} |",
      s"| modifier slots | ${allSlots.size} |",
      s"| distinct slot domains | ${allSlots.distinct.size} |",
      s"| typed slot names | ${derived.namedSlots.size} |",
      s"| types | ${derived.types.size} |",
      s"| special registers | ${derived.tables.special.size} |",
      s"| operand type rows | ${derived.rules.bindings.size} |",
      s"| operand value rows | ${derived.rules.values.size} |",
      s"| findings | ${derived.findings.size} |",
      s"| unresolved | ${unresolved(derived).size} |"
    )
    val rows = derived.rules.values.map { row =>
      val condition =
        (row.any.map(name => s"any .$name") ++ row.all.map(name => s"all .$name") ++
          row.none.map(name => s"no .$name")).mkString(", ")
      val check = row.kind match {
        case "range"    => s"${row.values.head}..${row.values(1)}"
        case "multiple" => s"multiple of ${row.values.head}"
        case "oneof"    => row.values.mkString("one of ", ", ", "")
        case _          => if (row.values.isEmpty) "power of two" else s"power of two up to ${row.values.head}"
      }
      s"| ${row.opcodes.mkString(", ")} | ${row.position} | ${if (condition.isEmpty) "" else condition} | $check${
          if (row.elements) " per element" else ""
        } | ${row.cite.section} |"
    }
    val table    = RuleHeader ++ rows
    val findings = FindingsHeader ++
      derived.findings.groupBy(identity).toVector
        .sortBy((finding, _) => (finding.check, finding.subject)).map { (finding, occurrences) =>
          s"- ${finding.check} `${finding.subject}`: ${finding.detail} -> ${finding.resolution.getOrElse("UNRESOLVED")}" +
            (if (occurrences.size > 1) s" (${occurrences.size})" else "")
        }
    (Rules ++ summary ++ table ++ findings).mkString("\n") + "\n"
  }
}
