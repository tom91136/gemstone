package net.kurobako.gemstone.codegen

import java.nio.file.Path
import net.kurobako.gemstone.collection.*

/** Generates the shared PTX and Scala inputs for the mma.m8n8k4 oracle. */
object GenerateMMA884Oracle {
  private enum Accumulator(val scala: String, val ptx: String) {
    case F32 extends Accumulator("F32", "f32")
    case F16 extends Accumulator("F16", "f16")
  }
  private enum Layout(val scala: String, val ptx: String) {
    case Row extends Layout("Row", "row")
    case Col extends Layout("Col", "col")
  }
  private enum Mode(val scala: String, val ptx: String) {
    case Plain     extends Mode("Plain", "plain")
    case Alias     extends Mode("Alias", "alias")
    case ZeroAlias extends Mode("ZeroAlias", "zeroalias")
  }

  private case class Variant(accum: Accumulator, a: Layout, b: Layout, mode: Mode) {
    val name: String   = s"mma884_${accum.ptx}_${a.ptx}_${b.ptx}_${mode.ptx}"
    val registers: Int = if (accum == Accumulator.F32) 8 else 4
  }

  private def variants: Vec[Variant] =
    for {
      accum <- Vec(Accumulator.F32, Accumulator.F16)
      a     <- Vec(Layout.Row, Layout.Col)
      b     <- Vec(Layout.Row, Layout.Col)
      mode  <- Vec(Mode.Plain, Mode.Alias, Mode.ZeroAlias)
    } yield Variant(accum, a, b, mode)

  private def render(items: Vec[Variant]): String = {
    val header  = Vec(".version 7.8", ".target sm_70", ".address_size 64")
    val entries = items.flatMap { variant =>
      val n     = variant.registers
      val lines = Vec(
        s".visible .entry ${variant.name}(.param .u64 pa,.param .u64 pb,.param .u64 pc,.param .u64 pd) {",
        ".reg .b64 %p<4>,%off;",
        ".reg .u32 %lane;",
        ".reg .b32 %a<2>,%b<2>;",
        s".reg .b32 %c<$n>,%d<$n>;",
        "ld.param.u64 %p0,[pa]; ld.param.u64 %p1,[pb]; ld.param.u64 %p2,[pc]; ld.param.u64 %p3,[pd];",
        "mov.u32 %lane,%laneid; mul.wide.u32 %off,%lane,8;",
        "add.u64 %p0,%p0,%off; add.u64 %p1,%p1,%off;",
        "ld.global.b32 %a0,[%p0]; ld.global.b32 %a1,[%p0+4];",
        "ld.global.b32 %b0,[%p1]; ld.global.b32 %b1,[%p1+4];",
        s"mul.wide.u32 %off,%lane,${n * 4}; add.u64 %p2,%p2,%off; add.u64 %p3,%p3,%off;"
      ) ++
        (if (variant.mode == Mode.ZeroAlias) Vec.from((0 until n).map(i => s"mov.b32 %c$i,0;"))
         else Vec.from((0 until n).map(i => s"ld.global.b32 %c$i,[%p2+${i * 4}];"))) ++ Vec(
          s"mma.sync.aligned.m8n8k4.${variant.a.ptx}.${variant.b.ptx}.${variant.accum.ptx}.f16.f16.${variant.accum.ptx} {${(0 until
              n).map(i => s"%${if (variant.mode == Mode.Plain) "d" else "c"}$i").mkString(",")}}, {%a0,%a1}, {%b0,%b1}, {${(0 until
              n).map(i => s"%c$i").mkString(",")}};"
        ) ++ Vec.from((0 until n).map(i =>
          s"st.global.b32 [%p3+${i * 4}],%${if (variant.mode == Mode.Plain) "d" else "c"}$i;"
        )) ++ Vec("ret;", "}")
      lines
    }
    (header ++ entries).mkString("\n") + "\n"
  }

  private def scalaString(value: String): String =
    "\"" + value.flatMap {
      case '\\' => "\\\\"
      case '"'  => "\\\""
      case '\n' => "\\n"
      case '\r' => "\\r"
      case c    => c.toString
    } + "\""

  private def renderScala: String = {
    val values = variants.map { variant =>
      s"    Variant(Accumulator.${variant.accum.scala}, Layout.${variant.a.scala}, Layout.${variant.b.scala}, Mode.${variant.mode.scala}, ${scalaString(variant.name)}: NonEmpty[String])"
    }.mkString(",\n")
    s"""package net.kurobako.gemstone.isa.ptx
       |
       |import net.kurobako.gemstone.collection.*
       |import net.kurobako.gemstone.constraint.*
       |
       |/** Generated by GenerateMMA884Oracle from the shared MMA884 fixture model. */
       |object Mma884Oracle {
       |  enum Accumulator { case F32, F16 }
       |  enum Layout { case Row, Col }
       |  enum Mode { case Plain, Alias, ZeroAlias }
       |  case class Variant(accum: Accumulator, aLayout: Layout, bLayout: Layout, mode: Mode, entryName: NonEmpty[String])
       |  val resource = "/mma884/oracle.ptx"
       |  val variants: Vec[Variant] = Vec(
       |$values
       |  )
       |}
       |""".stripMargin
  }

  def main(arguments: Array[String]): Unit = {
    require(arguments.length == 3, "expected generated-source-root generated-resource-root conformance-cuda-source-dir")
    val sourceRoot     = Path.of(arguments(0))
    val resourceRoot   = Path.of(arguments(1))
    val conformanceDir = Path.of(arguments(2))
    val fullPTX        = render(variants)
    val scalaOutput    = sourceRoot.resolve("net/kurobako/gemstone/isa/ptx/Mma884Oracle.scala")
    val _              = GeneratedFiles.write(scalaOutput, GeneratedScalaFormatter(scalaOutput, renderScala))
    val _              = GeneratedFiles.write(resourceRoot.resolve("mma884/oracle.ptx"), fullPTX)
    val _              = GeneratedFiles.write(conformanceDir.resolve("mma884.ptx"), fullPTX)
  }
}
