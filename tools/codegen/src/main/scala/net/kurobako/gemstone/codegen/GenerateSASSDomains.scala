package net.kurobako.gemstone.codegen

import scala.collection.mutable
import upickle.default.*

/** Renders the typed operand domains of every SASS description and the report of where its sources disagree. */
object GenerateSASSDomains {
  case class Output(json: String, report: String)

  private class Interner[A] {
    private val ids          = mutable.HashMap.empty[A, Int]
    private val values       = mutable.ArrayBuffer.empty[A]
    def apply(value: A): Int = ids.getOrElseUpdate(value, { values += value; values.size - 1 })
    def result: Vector[A]    = values.toVector
  }

  private case class Summary(digest: String, targets: Vector[String], derived: SASSOperandDomains.Derived)

  def render(tables: Vector[(String, SASSDescription.Description)], targets: Vector[(String, String)]): Output = {
    val byDigest  = targets.groupMap(_._2)(_._1)
    val summaries = tables.map { (digest, description) =>
      Summary(
        digest,
        byDigest.getOrElse(digest, Vector.empty),
        SASSOperandDomains.derive(description)
      )
    }
    check(summaries)
    Output(json(summaries), report(summaries))
  }

  def unresolved(derived: Vector[SASSOperandDomains.Derived]): Vector[DomainFinding] =
    derived.flatMap(_.findings).filter(_.resolution.isEmpty).distinct

  private def check(summaries: Vector[Summary]): Unit =
    OperandDomain.requireResolved("SASS", unresolved(summaries.map(_.derived)))

  private def json(summaries: Vector[Summary]): String = {
    val domains    = Interner[(String, OperandDomain)]()
    val signatures = Interner[Vector[(String, Int)]]()
    val tables     = summaries.map { summary =>
      val rows = summary.derived.forms.map { form =>
        val fields = form.fields.map(field => field.binding -> domains(field.label -> field.domain))
        ujson.write(ujson.Arr(form.name, signatures(fields)))
      }
      s"""{"digest": ${ujson.write(summary.digest)}, "forms": [${rows.mkString(",")}]}"""
    }
    val banks    = summaries.flatMap(_.derived.banks).groupMapReduce(_._1)(_._2)(_ max _).toVector.sortBy(_._1)
    val sections = Vector(
      "banks"   -> banks.map((bank, size) => s"""{"bank": ${ujson.write(bank)}, "size": $size}"""),
      "domains" -> domains.result.map((label, domain) =>
        s"""{"label": ${ujson.write(label)}, "domain": ${ujson.write(writeJs(domain))}}"""
      ),
      "signatures" -> signatures.result.map(fields =>
        ujson.write(ujson.Arr.from(fields.map((binding, id) => ujson.Arr(binding, id))))
      ),
      "tables" -> tables
    )
    sections.map((name, rows) => s"""  ${ujson.write(name)}: [\n${rows.map("    " + _).mkString(",\n")}\n  ]""")
      .mkString("{\n", ",\n", "\n}\n")
  }

  private val Rules = Vector(
    "# SASS operand domains",
    "",
    "Generated by `sbt codegen`; do not edit.",
    "",
    "## Rules",
    "",
    "- The pinned nvdisasm descriptions decide. A field takes the values of its FORMAT kind's vocabulary,",
    "  `INVALID*` placeholders excluded.",
    "- The ENCODING section gives the bits a form stores a field in. A vocabulary wider than the stored field is",
    "  narrowed to the codes the field holds, so `BD` barriers are B0 to B15 in a 4-bit field.",
    "- An `OOR_REG_ERROR` condition of the shape `Rx == RZ || Rx <= MAX_REG_COUNT - 1` bounds the register file of",
    "  that field below the vocabulary, and `Rx != R254` removes R254. Uniform registers use",
    "  `MAX_UNIFORM_REG_COUNT`.",
    "- Immediate widths come from the kind's argument. A narrower stored width, after the `SCALE` shift, wins.",
    "- A disagreement no rule resolves fails the build.",
    ""
  )

  private val SummaryHeader = Vector(
    "## Summary",
    "",
    "| table | targets | forms | typed fields | findings | unresolved |",
    "| --- | --- | ---: | ---: | ---: | ---: |"
  )

  private val FindingsHeading = Vector("", "## Findings", "")

  private def report(summaries: Vector[Summary]): String = {
    val rows = summaries.map { summary =>
      val derived = summary.derived
      s"| ${summary.digest.take(8)} | ${targetRange(summary.targets)} | ${derived.forms.size} | " +
        s"${derived.forms.map(_.fields.size).sum} | ${derived.findings.size} | " +
        s"${derived.findings.count(_.resolution.isEmpty)} |"
    }
    val grouped = summaries.flatMap(summary => summary.derived.findings.map(_ -> summary.digest))
      .groupBy(_._1).toVector.sortBy((finding, _) => (finding.check, finding.subject, finding.detail))
    val findings = grouped.map { (finding, occurrences) =>
      val tables = occurrences.map(_._2).distinct.size
      s"- ${finding.check} `${finding.subject}`: ${finding.detail} -> ${finding.resolution.getOrElse("UNRESOLVED")} " +
        s"(${occurrences.size} fields, $tables tables)"
    }
    (Rules ++ SummaryHeader ++ rows ++ FindingsHeading ++ findings).mkString("\n") + "\n"
  }

  private def targetRange(targets: Vector[String]): String = targets match {
    case Vector()  => ""
    case Vector(x) => x
    case _         => s"${targets.head} to ${targets.last} (${targets.size})"
  }
}
