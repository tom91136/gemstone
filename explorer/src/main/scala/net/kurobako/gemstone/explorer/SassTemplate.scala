/** Synthetic SASS templates: cubins whose kernel code the sandbox replaces with an assembled sequence. The sm_89
  * `copy_add` kernel is the same ptxas image the samples project uses, copied here so the explorer does not depend on
  * that project; its two parameters are 64-bit addresses, which [[ProgramRun]] materialises as allocations.
  */
object SassTemplate {

  /** A template image and the kernel whose code may be replaced. */
  case class Image(bytes: Vec[Byte], kernel: NonEmpty[String], target: Target) derives CanEqual

  /** The sm_50 `ld128_uniform` cubin the Program page already loads; its first entry point takes two pointers. */
  lazy val sm50: Image =
    decode(Hex.parse(SassExample.cubin).fold(error => throw IllegalArgumentException(error), identity))

  /** The sm_89 `copy_add` cubin compiled by ptxas 13.3 from the samples project's source. */
  lazy val sm89: Image = decode(Hex.parse(sm89Cubin).fold(error => throw IllegalArgumentException(error), identity))

  private def decode(bytes: Vec[Byte]): Image =
    Cubin.decode(bytes).fold(
      error => throw IllegalArgumentException(error),
      module =>
        Image(
          bytes,
          module.kernels.head.name,
          Target.of(module.sm).fold(error => throw IllegalArgumentException(error), identity)
        )
    )

