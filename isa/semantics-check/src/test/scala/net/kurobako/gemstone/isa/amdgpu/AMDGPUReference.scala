/** Executes an instruction instance on the VM: its operands and state take the inputs, as do the other lanes of its
  * vector registers by [[AMDGPUHarness.held]], EXEC activates [[AMDGPUHarness.Lane]] only unless the instance reads it,
  * and the results are read from that lane.
  */
private[isa] object AMDGPUReference extends Reference[AMDGPUHarness, Lookup.Spellings] {
  import AMDGPUHarness.*

  def harness(seed: Long): AMDGPUHarness = AMDGPUHarness()

  // the machine state is compared as a value of any shape
  @SuppressWarnings(Array("scalafix:PublicSignatures.any-type"))
  def state(harness: AMDGPUHarness): Any = harness.writes

  private val Single = raw"([sva])(\d+)".r
  private val Range  = raw"([sva])\[(\d+):(\d+)\]".r

  private val ImplicitNames = ImplicitState.names.toSet
  private val NumericCodes  = Vec(0L, 1L, 2L, 3L, 4L, 5L, 7L, 9L)

  /** Where a name lives: implicit state, a register file's first register, or the instruction's literal. */
  private enum Location {
    case State(name: String)
    case Register(file: Char, index: Int)
    case Literal
  }

  private def location(spellings: Iterable[String]): Option[Location] = spellings.view.map {
    case Single(file, index)                 => Some(Location.Register(file.head, index.toInt))
    case Range(file, index, _)               => Some(Location.Register(file.head, index.toInt))
    case state if ImplicitNames(state)       => Some(Location.State(state))
    case literal if literal.startsWith("0x") => Some(Location.Literal)
    case _                                   => None
  }.collectFirst { case Some(found) => found }

  private def dwords(tpe: Type): Int = (tpe.bits + 31) / 32

  private val Word       = raw"S?RSRC(?:\+(\d))?".r
  private val Coordinate = raw"VADDR[0-9A-D]?(?:\+\d)?|v\d+".r

  private val Relative = "v_(?:movrel|swaprel).*".r

  /** A relative move's M0, which offsets VGPRs well clear of the registers its operands name and the reference uses:
    * each field of the pair moves, with junk in the bits it ignores, or the whole register.
    */
  private def offsets(instance: String, random: Random): Long = {
    def small = 64L + random.nextInt(56)
    if (instance.startsWith("v_movrelsd_2") || instance.startsWith("v_swaprel"))
      small | (small << 16) | (random.nextLong() & 0xfc00fc00L)
    else small
  }

  /** Image instances read a linear image descriptor, generated by [[descriptor]], and coordinates small enough to fall
    * inside it as often as not; relative moves read an M0 that offsets into registers that hold only their
    * [[AMDGPUHarness.background]]; other instances read the sampled inputs.
    */
  override def inputs(
      target: Option[String],
      instance: String,
      lookup: Lookup.Spellings,
      parameters: Vec[(String, Type)],
      sampled: Vec[Long],
      random: Random
  ): Vec[Long] = if (Relative.matches(instance))
    parameters.zip(sampled).map { case ((parameter, _), value) =>
      val spellings = lookup.operands.collect { case (spelling, key) if key == parameter => spelling }.toVec :+
        parameter
      if (location(spellings).contains(Location.State(RenderContext.M0))) offsets(instance, random) else value
    }
  else
    target.flatMap(_.refine[Target].toOption).filter(_ => instance.startsWith("image_")).fold(sampled) { selected =>
      val words  = descriptor(selected.isa, random)
      val halves = instance.contains(" a16") || instance.contains(" r128")
      def small  = random.nextInt(10).toLong
      parameters.zip(sampled).map {
        case ((Word(offset), _), _) => words(Option(offset).fold(0)(_.toInt))
        case ((Coordinate(), _), _) => if (halves) small | (small << 16) else small
        case (_, value)             => value
      }
    }

  /** Eight dwords of a linear image descriptor on `isa` of a format execution reads, of up to 8 by 8 by 8 texels or
    * layers and a few levels, with random selects, base and pitch.
    */
  private def descriptor(isa: ISA, random: Random): Vec[Long] = {
    import ResourceGeneration.*
    val generation                                     = ResourceGeneration.of(isa)
    def pick(codes: Range, valid: Int => Boolean): Int =
      Iterator.continually(codes(random.nextInt(codes.size))).find(valid).get
    val base                    = random.nextLong() & 0xffffffffffL
    val width                   = random.nextInt(8).toLong
    val height                  = random.nextInt(8).toLong
    val (firstLevel, lastLevel) = {
      val first = random.nextInt(2).toLong
      (first, first + random.nextInt(3))
    }
    val selects = random.nextLong() & 0xfffL
    val kind    = 8L + random.nextInt(6)
    val format  = generation match {
      case GFX8 | GFX9 =>
        val data    = pick(1 to 14, code => TexelFormat.legacy(code, 0).valid).toLong
        val numeric = NumericCodes(random.nextInt(8))
        if (TexelFormat.legacy(data.toInt, numeric.toInt).valid) (data << 20) | (numeric << 26) else data << 20
      case GFX10 => pick(1 to 140, code => TexelFormat.unified(generation, code).valid).toLong << 20
      case GFX11 => pick(1 to 75, code => TexelFormat.unified(generation, code).valid).toLong << 20
      case GFX12 => pick(1 to 75, code => TexelFormat.unified(generation, code).valid).toLong << 17
    }
    val depth          = random.nextInt(8).toLong
    val pitch          = random.nextInt(16).toLong
    val array          = random.nextInt(3).toLong
    val (word2, word3) = generation match {
      case GFX8 | GFX9 => (width | (height << 14), selects | (firstLevel << 12) | (lastLevel << 16))
      case GFX12       => ((width >>> 2) | (height << 14), selects | (lastLevel << 15))
      case _           => ((width >>> 2) | (height << 14), selects | (firstLevel << 12) | (lastLevel << 16))
    }
    val word1 = (base >>> 32) | format |
      (generation match {
        case GFX8 | GFX9 => 0L
        case GFX12       => ((width & 3L) << 30) | (firstLevel << 25)
        case _           => (width & 3L) << 30
      })
    val (word4, word5) = generation match {
      case GFX8  => (depth | (pitch << 13), array | (random.nextInt(4).toLong << 13))
      case GFX9  => (depth | (pitch << 13), array)
      case GFX12 => (depth | (array << 16), 0L)
      case _     => (depth | (array << 16), 0L)
    }
    Vec(
      base & 0xffffffffL,
      word1,
      word2,
      word3 | (kind << 28) | (if (generation == GFX8) 8L << 20 else 0L),
      word4,
      word5,
      0L,
      0L
    )
  }

  private val VccCopy: ScalarRegisterIndex  = 100
  private val SccCopy: ScalarRegisterIndex  = 102
  private val Spare: VectorRegisterIndex    = 255
  private val Readback: VectorRegisterIndex = 200
  private val Written: VectorRegisterIndex  = 250

  /** The registers of [[AMDGPUHarness.Lane]] and EXEC as the wave reaches the instruction at byte offset `end`. */
  private class Ended(end: Long) extends LaunchObserver {
    val scalars: Array[Long] = Array.ofDim[Long](128)
    val vectors: Array[Long] = Array.ofDim[Long](256)
    val exec: Array[Long]    = Array.ofDim[Long](1)

    def instruction(at: Fault.Location, state: ArchitecturalState): Either[Fault, Unit] = {
      (at.instruction, state) match {
        case (Some(offset), view: WaveView) if offset.raw == end =>
          (0 until 128).foreach(index => scalars(index) = view.scalar(index.unsafe[Int in 0 ~ 127]))
          (0 until 256).foreach(index => vectors(index) = view.vector(index.unsafe[Int in 0 ~ 255], Lane))
          exec(0) = view.exec
        case _ => ()
      }
      Right(())
    }
  }

  private val encoded = TrieMap.empty[(String, String), Either[String, Vec[Byte]]]

  def execute(
      target: Option[String],
      instance: String,
      lookup: Lookup.Spellings,
      parameters: Vec[(String, Type)],
      inputs: Vec[Long],
      results: Vec[(String, Type)],
      harness: AMDGPUHarness
  ): Either[String, Vec[Long]] = for {
    name     <- target.toRight("AMDGPU instances run on a target")
    selected <- name.refine[Target].left.map(_.raw)
    named = (key: String) => lookup.operands.collect { case (spelling, value) if value == key => spelling }.toVec :+ key
    code <- encoded.getOrElseUpdate(
      (name, instance),
      for {
        program <- asm.Parser.parse(instance).left.map(_.diagnostic.raw)
        code    <- asm.Assembler.encode(program, selected, TargetDefaults.waveSize(selected)).left.map(_.toString)
      } yield code
    )
    literal = parameters.zip(inputs).collectFirst {
      case ((parameter, _), value) if location(named(parameter)).contains(Location.Literal) => value
    }
    patched     <- literal.fold(Right(code))(value => patch(code, value))
    instruction <- VMCompiler.decodeInstruction(patched, selected).left.map(_.raw)
    ended       <- run(
      selected,
      instruction,
      parameters.zip(inputs).map((parameter, value) => (named(parameter._1), parameter._2, value)),
      results.map((result, tpe) => (named(result), tpe)),
      harness
    )
  } yield ended

  /** `code` with its trailing literal dword, which the explorer spells `0x1234`, replaced by `value`. */
  private def patch(code: Vec[Byte], value: Long): Either[String, Vec[Byte]] = {
    val at = code.size - 4
    Either.cond(
      at >= 4 && LittleEndian.decode(code, at, 4) == 0x1234L,
      Vec.tabulate(code.size)(index =>
        if (index < at) code(index) else ((value >>> ((index - at) * 8)) & 0xffL).toByte
      ),
      s"no trailing literal in ${code.map(byte => f"$byte%02x").mkString(" ")}"
    )
  }

  /** The registers [[offsets]] reaches, which no operand names. */
  private val RelativeFirst = 64
  private val RelativeEnd   = 200

  /** The fields of M0 that offset the registers `instruction` reaches. */
  private def relativeFields(instruction: Instruction): Set[RelativeField] = instruction match {
    case Instruction.VMoveRelative(field = field)                                  => Set(field)
    case Instruction.VMoveRelativeDestination(sourceField = source, field = field) => source.toSet + field
    case Instruction.VSwapRelative(dest = _)                   => Set(RelativeField.Source, RelativeField.Destination)
    case Instruction.VDPP(operation = inner, relative = field) => field.toSet ++ relativeFields(inner)
    case Instruction.VSubDwordResult(operation = inner, relative = field) => field.toSet ++ relativeFields(inner)
    case _                                                                => Set.empty
  }

  private def run(
      target: Target,
      instruction: Instruction,
      inputs: Vec[(Vec[String], Type, Long)],
      results: Vec[(Vec[String], Type)],
      harness: AMDGPUHarness
  ): Either[String, Vec[Long]] = {
    val waveSize = TargetDefaults.waveSize(target)
    val wide     = waveSize == 64
    val seeds    = Vec.newBuilder[Instruction]
    // the registers a relative move reaches hold what the definitions' wave holds in each lane, which DPP routes
    val fields = relativeFields(instruction)
    if (fields.nonEmpty)
      for {
        index <- 0 until 256
        lane  <- 0 until waveSize
      } seeds += Instruction.VWriteLane(
        index.unsafe[VectorRegisterIndex],
        InstructionSource.Constant(background(index, lane)),
        InstructionSource.Constant(lane.toLong)
      )
    // the matrix core runs only on a complete active wave64
    val exec = inputs.collectFirst {
      case (spellings, _, value) if location(spellings).contains(Location.State(RenderContext.Exec)) => value
    }.getOrElse(instruction match {
      case Instruction.VMatrix(shape = shape) if shape.layout == MatrixLayout.Core => -1L
      case _                                                                       => 1L << Lane
    })
    def input(register: VectorRegisterIndex): Long = {
      val wanted = Location.Register('v', register)
      inputs.collectFirst { case (spellings, _, value) if location(spellings).contains(wanted) => value }.getOrElse(0L)
    }
    // what an instruction writes to LDS is read back from the offsets it addressed
    def readBack(register: VectorRegisterIndex, displacement: Int, bytes: Int): (Long, MemoryAddress, Int) =
      (
        Execute.ldsOffset(Bits.low32(input(register)).toLong + displacement),
        MemoryAddress.Local(register, displacement),
        bytes
      )
    def m0: Long = inputs.collectFirst {
      case (spellings, _, value) if location(spellings).contains(Location.State(RenderContext.M0)) => value
    }.getOrElse(0L)
    val shared = instruction match {
      case Instruction.Store(address = MemoryAddress.Local(register, displacement), bytes = bytes) =>
        Vec(readBack(register, displacement, bytes))
      case Instruction.StorePair(address = address, bytes = bytes, first = first, second = second) =>
        Vec(readBack(address, first, bytes), readBack(address, second, bytes))
      // an ADDTID store writes at M0[15:0] plus its offset plus the lane's four bytes, which a seeded VGPR addresses
      case Instruction.Store(address = MemoryAddress.LaneLocal(offset), bytes = bytes) =>
        val at = Execute.laneLocalAddress(Bits.low32(m0).toLong, offset.toLong, Lane.toLong)
        seeds +=
          Instruction.VWriteLane(Written, InstructionSource.Constant(at), InstructionSource.Constant(Lane.toLong))
        Vec((at, MemoryAddress.Local(Written, 0), bytes.raw))
      case Instruction.Atomic(address = MemoryAddress.Local(register, displacement), bytes = bytes) =>
        Vec(readBack(register, displacement, bytes))
      case Instruction.CompareSwap(address = MemoryAddress.Local(register, displacement), bytes = bytes) =>
        Vec(readBack(register, displacement, bytes))
      case Instruction.LocalSource2(address = register, bytes = bytes) => Vec(readBack(register, 0, bytes))
      case extended @ Instruction.AtomicExtended(
            access = Instruction.CompareSwap(address = MemoryAddress.Local(register, offset))
          ) =>
        Vec(readBack(register, offset, extended.access.bytes))
      case Instruction.ExchangePair(first, second) =>
        Vec(first, second).collect { case Instruction.Atomic(address = MemoryAddress.Local(register, offset)) =>
          readBack(register, offset, first.bytes)
        }
      // a buffer load into LDS writes at M0 plus its offset plus the lane's stride, which a seeded VGPR addresses
      case Instruction.LoadLocal(bytes = bytes, offset = offset) =>
        val at = Execute.ldsOffset(Bits.low32(m0).toLong + offset + Lane * math.max(4, bytes))
        seeds +=
          Instruction.VWriteLane(Written, InstructionSource.Constant(at), InstructionSource.Constant(Lane.toLong))
        Vec((at, MemoryAddress.Local(Written, 0), bytes.raw))
      case _ => Vec.empty[(Long, MemoryAddress, Int)]
    }
    // a definition that ignores M0 names none, so the offsets it should apply are seeded all the same
    if (
      fields.nonEmpty &&
      !inputs.exists((spellings, _, _) => location(spellings).contains(Location.State(RenderContext.M0)))
    )
      seeds += Instruction.SMove(
        m0Register(target.isa),
        InstructionSource.Constant(if (fields.exists(_ != RelativeField.Whole)) 0x460046L else 70L)
      )
    inputs.foreach { (spellings, tpe, value) =>
      location(spellings) match {
        case Some(Location.State(RenderContext.Scc)) =>
          seeds += Instruction.SCmp(
            ScalarCompareOperation.EqualU32,
            InstructionSource.Constant(1L),
            InstructionSource.Constant(value)
          )
        case Some(Location.State(RenderContext.Vcc)) =>
          seeds +=
            (if (wide) Instruction.SMove64(Fixed.VccLo, InstructionSource.Constant(value))
             else Instruction.SMove(Fixed.VccLo, InstructionSource.Constant(value)))
        case Some(Location.State(RenderContext.M0)) => seeds +=
            Instruction.SMove(m0Register(target.isa), InstructionSource.Constant(value))
        case Some(Location.State(RenderContext.Mode)) => seeds +=
            Instruction.SSetMode(0, 32, InstructionSource.Constant(value))
        case Some(Location.Register('s', index)) =>
          (0 until dwords(tpe)).foreach(offset =>
            seeds += Instruction.SMove(
              (index + offset).unsafe[ScalarRegisterIndex],
              InstructionSource.Constant(Bits.low32(value >>> (offset * 32)).toLong)
            )
          )
        case Some(Location.Register(file, index)) =>
          (0 until dwords(tpe)).foreach { offset =>
            val dword  = Bits.low32(value >>> (offset * 32)).toLong
            val target = if (file == 'a') Spare else (index + offset).unsafe[VectorRegisterIndex]
            (0 until waveSize).foreach(lane =>
              seeds += Instruction.VWriteLane(
                target,
                InstructionSource.Constant(held(dword, lane)),
                InstructionSource.Constant(lane.toLong)
              )
            )
            if (file == 'a') seeds += Instruction.VAccumulatorWrite(
              (index + offset).unsafe[VectorRegisterIndex],
              InstructionSource.VectorRegister(Spare)
            )
          }
        case _ => ()
      }
    }
    seeds +=
      (if (wide) Instruction.SMove64(Fixed.ExecLo, InstructionSource.Constant(exec))
       else Instruction.SMove(Fixed.ExecLo, InstructionSource.Constant(exec)))
    val accumulators = results.flatMap((spellings, tpe) =>
      location(spellings) match {
        case Some(Location.Register('a', index)) => Vec.tabulate(dwords(tpe))(index + _)
        case _                                   => Vec.empty[Int]
      }
    )
    val captures = Vec(
      Instruction.SMove64(VccCopy, InstructionSource.Scalar(Fixed.VccLo)),
      Instruction.SCSelect(SccCopy, InstructionSource.Constant(1L), InstructionSource.Constant(0L), 32)
    ) ++ accumulators.zipWithIndex.map((index, offset) =>
      Instruction.VAccumulatorRead(
        (Spare - 1 - offset).unsafe[VectorRegisterIndex],
        index.unsafe[VectorRegisterIndex]
      )
    ) ++ shared.zipWithIndex.map { case ((_, address, bytes), index) =>
      Instruction.Load(
        Readback.offsetBy((index * 4).unsafe[Int >= 0]),
        address,
        bytes.unsafe[Int in 1 ~ 16],
        signed = false,
        LoadPlacement.Full
      )
    }
    val operations = seeds.result() ++ Vec(instruction) ++ captures ++ Vec(Instruction.End)
    val ended      = Ended((operations.size - 1) * 4L)
    val source     = codeKernel(
      target = target,
      groupSegmentSize = LdsBytes,
      privateSegmentSize = 4096,
      kernelCodeProperties = if (waveSize == 32) KernelCodeProperty.ENABLE_WAVEFRONT_SIZE32 else 0
    )
    val task = KernelTask.validated("kernel", Dimensions(waveSize.widen[Int > 0], 1, 1), Dimensions.One, Vec.empty)
    for {
      dispatch <- task.left.map(_.raw)
      _        <- VMInterpreter.execute(
        irKernel(operations, source),
        dispatch,
        AMDGPUGlobalSpace(harness.globalBytes),
        TaskControl(observer = Some(ended)),
        Workgroups.Sequential,
        Vec.empty,
        _ => Right(())
      ).left.map(_.toString)
    } yield {
      if (fields.nonEmpty)
        (RelativeFirst until RelativeEnd).foreach { index =>
          val value = Bits.low32(ended.vectors(index)).toLong
          if (value != background(index, Lane)) harness.writeVector(index, value)
        }
      shared.zipWithIndex.foreach { case ((at, _, bytes), index) =>
        (0 until (bytes + 3) / 4).foreach(dword =>
          harness.sharedBytes.store(
            at + dword * 4,
            ended.vectors(Readback + index * 4 + dword),
            math.min(4, bytes - dword * 4)
          )
        )
      }
      results.map { (spellings, tpe) =>
        def dword(index: Int): Long = Bits.low32(ended.scalars(index)).toLong
        val value                   = location(spellings) match {
          case Some(Location.State(RenderContext.Scc))  => ended.scalars(SccCopy)
          case Some(Location.State(RenderContext.Vcc))  => dword(VccCopy) | (dword(VccCopy + 1) << 32)
          case Some(Location.State(RenderContext.Exec)) => ended.exec(0)
          case Some(Location.State(_))                  => dword(m0Register(target.isa))
          case Some(Location.Register('s', index))      =>
            if (dwords(tpe) == 2) dword(index) | (dword(index + 1) << 32) else dword(index)
          case Some(Location.Register('a', index)) =>
            val offset = accumulators.indexOf(index)
            Bits.low32(ended.vectors(Spare - 1 - offset)).toLong |
              (if (dwords(tpe) == 2) Bits.low32(ended.vectors(Spare - 2 - offset)).toLong << 32 else 0L)
          case Some(Location.Register(_, index)) =>
            Bits.low32(ended.vectors(index)).toLong |
              (if (dwords(tpe) == 2) Bits.low32(ended.vectors(index + 1)).toLong << 32 else 0L)
          case _ => 0L
        }
        tpe.represent(value)
      }
    }
  }
}
