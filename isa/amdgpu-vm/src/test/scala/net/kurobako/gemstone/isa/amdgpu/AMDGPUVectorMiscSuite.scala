    assertEquals(permuted(Target("gfx1100"), code, wave32 = false), Vec.tabulate(64)(lane => (lane ^ 32) * 10L))
    assertEquals(permuted(Target("gfx1100"), code).take(32), Vec.fill(32)(0xdeadL))
  }

