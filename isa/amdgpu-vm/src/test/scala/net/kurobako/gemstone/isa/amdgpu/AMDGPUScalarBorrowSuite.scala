package net.kurobako.gemstone.isa.amdgpu

import VMIR.*
import laneRuns.*
import net.kurobako.gemstone.collection.*
import net.kurobako.gemstone.constraint.*
import net.kurobako.gemstone.testing.*

/** SCC after `s_sub_u32` and `s_subb_u32` is the borrow out. Rows are the dword results of
  * `s_sub_u32 s4, s0, s1; s_cselect_b32 s5, 1, 0; s_sub_u32 s4, s0, s1; s_subb_u32 s8, s2, s3; s_cselect_b32 s9, 1, 0`
  * on a gfx1036 with s0 to s3 holding the first four columns, run through `hipcc --offload-arch=gfx1036` inline
  * assembly; the machine code is from `llvm-mc -show-encoding` for each target.
  */
class AMDGPUScalarBorrowSuite extends Suite {
  private val encodings = Seq(
    Target("gfx900") -> Vec(
      0x00, 0x01, 0x84, 0x80, 0x81, 0x80, 0x05, 0x85, 0x00, 0x01, 0x84, 0x80, 0x02, 0x03, 0x88, 0x82, 0x81, 0x80, 0x09,
      0x85
    ),
    Target("gfx1030") -> Vec(
      0x00, 0x01, 0x84, 0x80, 0x81, 0x80, 0x05, 0x85, 0x00, 0x01, 0x84, 0x80, 0x02, 0x03, 0x88, 0x82, 0x81, 0x80, 0x09,
      0x85
    ),
    Target("gfx1100") -> Vec(
      0x00, 0x01, 0x84, 0x80, 0x81, 0x80, 0x05, 0x98, 0x00, 0x01, 0x84, 0x80, 0x02, 0x03, 0x88, 0x82, 0x81, 0x80, 0x09,
      0x98
    ),
    Target("gfx1201") -> Vec(
      0x00, 0x01, 0x84, 0x80, 0x81, 0x80, 0x05, 0x98, 0x00, 0x01, 0x84, 0x80, 0x02, 0x03, 0x88, 0x82, 0x81, 0x80, 0x09,
      0x98
    )
  )

  private val rows = Seq(
    (Vec(0x0L, 0x1L, 0x5L, 0x5L), Vec(0xffffffffL, 1L, 0xffffffffL, 1L)),
    (Vec(0x1L, 0x0L, 0x5L, 0x5L), Vec(0x1L, 0L, 0x0L, 0L)),
    (Vec(0x5L, 0x5L, 0x5L, 0x5L), Vec(0x0L, 0L, 0x0L, 0L)),
    (Vec(0x5L, 0x3L, 0x0L, 0x0L), Vec(0x2L, 0L, 0x0L, 0L)),
    (Vec(0x3L, 0x5L, 0x0L, 0x0L), Vec(0xfffffffeL, 1L, 0xffffffffL, 1L)),
    (Vec(0xffffffffL, 0x0L, 0x0L, 0x0L), Vec(0xffffffffL, 0L, 0x0L, 0L)),
    (Vec(0x0L, 0xffffffffL, 0x0L, 0x0L), Vec(0x1L, 1L, 0xffffffffL, 1L)),
    (Vec(0x0L, 0x1L, 0x0L, 0x0L), Vec(0xffffffffL, 1L, 0xffffffffL, 1L)),
    (Vec(0x0L, 0x1L, 0x7L, 0x6L), Vec(0xffffffffL, 1L, 0x0L, 0L)),
    (Vec(0x5L, 0x3L, 0x7L, 0x7L), Vec(0x2L, 0L, 0x0L, 0L)),
    (Vec(0x3L, 0x5L, 0x7L, 0x7L), Vec(0xfffffffeL, 1L, 0xffffffffL, 1L))
  )

  for {
    (target, code)     <- encodings
    (inputs, expected) <- rows
  } test(s"$target s_sub_u32 and s_subb_u32 set SCC to the borrow for ${inputs.map(_.toHexString).mkString(",")}") {
    val operations = program(target, octets(code*))
    val results    = Vec(4, 5, 8, 9).map(result =>
      scalarResult(target, inputs, operations, result.unsafe[ScalarRegisterIndex])
    )
    assertEquals(results, expected)
  }
}
